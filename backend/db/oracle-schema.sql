-- Oracle schema definition for NewMen Store (32 core business tables + audit & auth tables)
-- Target: Oracle Database 19c / 21c / 23c

-- 1. Roles (Bảng 2.31)
CREATE TABLE roles (
  id NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  name VARCHAR2(50 CHAR) NOT NULL,
  description VARCHAR2(200 CHAR),
  status NUMBER(1) DEFAULT 1 NOT NULL,
  CONSTRAINT uk_role_name UNIQUE (name)
);

-- Authentication accounts
CREATE TABLE accounts (
  id NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  email VARCHAR2(255 CHAR) NOT NULL,
  password_hash VARCHAR2(100 CHAR) NOT NULL,
  full_name VARCHAR2(160 CHAR) NOT NULL,
  phone VARCHAR2(32 CHAR),
  role VARCHAR2(20 CHAR) NOT NULL,
  active NUMBER(1) DEFAULT 1 NOT NULL,
  created_at TIMESTAMP NOT NULL,
  CONSTRAINT uk_account_email UNIQUE (email)
);

-- 2. Employees (Bảng 2.12)
CREATE TABLE employees (
  id NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  name VARCHAR2(160 CHAR) NOT NULL,
  image VARCHAR2(255 CHAR),
  birth_date DATE,
  phone VARCHAR2(32 CHAR),
  email VARCHAR2(255 CHAR) NOT NULL,
  password VARCHAR2(100 CHAR) NOT NULL,
  role_id NUMBER,
  status NUMBER(1) DEFAULT 1 NOT NULL,
  address VARCHAR2(255 CHAR),
  account_id NUMBER,
  created_at TIMESTAMP NOT NULL,
  CONSTRAINT uk_employee_email UNIQUE (email),
  CONSTRAINT fk_employee_role FOREIGN KEY (role_id) REFERENCES roles(id),
  CONSTRAINT fk_employee_account FOREIGN KEY (account_id) REFERENCES accounts(id)
);

-- 3. Customers (Bảng 2.13)
CREATE TABLE customers (
  id NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  name VARCHAR2(160 CHAR) NOT NULL,
  image VARCHAR2(255 CHAR),
  birth_date DATE,
  phone_number VARCHAR2(32 CHAR),
  email VARCHAR2(255 CHAR) NOT NULL,
  password VARCHAR2(100 CHAR) NOT NULL,
  role_id NUMBER,
  status NUMBER(1) DEFAULT 1 NOT NULL,
  points NUMBER(10) DEFAULT 0 NOT NULL,
  account_id NUMBER,
  created_at TIMESTAMP NOT NULL,
  CONSTRAINT uk_customer_email UNIQUE (email),
  CONSTRAINT fk_customer_role FOREIGN KEY (role_id) REFERENCES roles(id),
  CONSTRAINT fk_customer_account FOREIGN KEY (account_id) REFERENCES accounts(id)
);

-- 4. Customer Addresses (Bảng 2.14)
CREATE TABLE customer_addresses (
  id NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  account_id NUMBER,
  customer_id NUMBER,
  recipient_name VARCHAR2(160 CHAR),
  phone VARCHAR2(32 CHAR),
  line1 VARCHAR2(255 CHAR),
  address VARCHAR2(255 CHAR),
  ward VARCHAR2(120 CHAR),
  ward_name VARCHAR2(120 CHAR),
  district VARCHAR2(120 CHAR),
  district_name VARCHAR2(120 CHAR),
  province VARCHAR2(120 CHAR),
  city_name VARCHAR2(120 CHAR),
  other VARCHAR2(255 CHAR),
  is_default NUMBER(1) DEFAULT 0 NOT NULL,
  status NUMBER(1) DEFAULT 1 NOT NULL,
  CONSTRAINT fk_address_account FOREIGN KEY (account_id) REFERENCES accounts(id),
  CONSTRAINT fk_address_customer FOREIGN KEY (customer_id) REFERENCES customers(id)
);

-- 5. Origin Categories (Bảng 2.22)
CREATE TABLE origin_categories (
  id NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  name_category_f VARCHAR2(120 CHAR) NOT NULL,
  status NUMBER(1) DEFAULT 1 NOT NULL
);

-- 6. Categories (Bảng 2.23)
CREATE TABLE categories (
  id NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  name VARCHAR2(120 CHAR) NOT NULL,
  name_category VARCHAR2(120 CHAR),
  slug VARCHAR2(150 CHAR) NOT NULL,
  parent_id NUMBER,
  origin_category_id NUMBER,
  active NUMBER(1) DEFAULT 1 NOT NULL,
  status NUMBER(1) DEFAULT 1 NOT NULL,
  CONSTRAINT uk_category_slug UNIQUE (slug),
  CONSTRAINT fk_category_parent FOREIGN KEY (parent_id) REFERENCES categories(id),
  CONSTRAINT fk_category_origin FOREIGN KEY (origin_category_id) REFERENCES origin_categories(id)
);

-- 7. Colors (Bảng 2.16)
CREATE TABLE colors (
  id NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  name_color VARCHAR2(60 CHAR) NOT NULL,
  code_hex VARCHAR2(20 CHAR),
  status NUMBER(1) DEFAULT 1 NOT NULL
);

-- 8. Sizes (Bảng 2.24)
CREATE TABLE sizes (
  id NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  code VARCHAR2(20 CHAR) NOT NULL,
  description VARCHAR2(255 CHAR),
  status NUMBER(1) DEFAULT 1 NOT NULL
);

-- 9. Materials (Bảng 2.20)
CREATE TABLE materials (
  id NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  name_material VARCHAR2(120 CHAR) NOT NULL,
  status NUMBER(1) DEFAULT 1 NOT NULL
);

-- 10. Collars (Bảng 2.18)
CREATE TABLE collars (
  id NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  name_collar VARCHAR2(120 CHAR) NOT NULL,
  status NUMBER(1) DEFAULT 1 NOT NULL
);

-- 11. Designs (Bảng 2.17)
CREATE TABLE designs (
  id NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  name_design VARCHAR2(120 CHAR) NOT NULL,
  status NUMBER(1) DEFAULT 1 NOT NULL
);

-- 12. Forms (Bảng 2.19)
CREATE TABLE forms (
  id NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  name_form VARCHAR2(120 CHAR) NOT NULL,
  status NUMBER(1) DEFAULT 1 NOT NULL
);

-- 13. Sleeves (Bảng 2.21)
CREATE TABLE sleeves (
  id NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  name_sleeve VARCHAR2(120 CHAR) NOT NULL,
  status NUMBER(1) DEFAULT 1 NOT NULL
);

-- 14. Products (Bảng 2.29)
CREATE TABLE products (
  id NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  slug VARCHAR2(150 CHAR) NOT NULL,
  code VARCHAR2(64 CHAR) NOT NULL,
  name VARCHAR2(200 CHAR) NOT NULL,
  description VARCHAR2(3000 CHAR),
  category_id NUMBER,
  material VARCHAR2(120 CHAR),
  material_id NUMBER,
  collar VARCHAR2(100 CHAR),
  collar_id NUMBER,
  design VARCHAR2(100 CHAR),
  design_id NUMBER,
  fit VARCHAR2(100 CHAR),
  form_id NUMBER,
  sleeve VARCHAR2(100 CHAR),
  sleeve_id NUMBER,
  original_price NUMBER(12,2),
  weight NUMBER(10,2) DEFAULT 200.0,
  active NUMBER(1) DEFAULT 1 NOT NULL,
  status NUMBER(1) DEFAULT 1 NOT NULL,
  created_at TIMESTAMP NOT NULL,
  CONSTRAINT uk_product_slug UNIQUE (slug),
  CONSTRAINT uk_product_code UNIQUE (code),
  CONSTRAINT fk_product_category FOREIGN KEY (category_id) REFERENCES categories(id),
  CONSTRAINT fk_product_material FOREIGN KEY (material_id) REFERENCES materials(id),
  CONSTRAINT fk_product_collar FOREIGN KEY (collar_id) REFERENCES collars(id),
  CONSTRAINT fk_product_design FOREIGN KEY (design_id) REFERENCES designs(id),
  CONSTRAINT fk_product_form FOREIGN KEY (form_id) REFERENCES forms(id),
  CONSTRAINT fk_product_sleeve FOREIGN KEY (sleeve_id) REFERENCES sleeves(id)
);

-- 15. Product Details / Variants (Bảng 2.30)
CREATE TABLE product_details (
  id NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  product_id NUMBER NOT NULL,
  sku VARCHAR2(64 CHAR) NOT NULL,
  barcode VARCHAR2(64 CHAR),
  color VARCHAR2(60 CHAR) NOT NULL,
  color_id NUMBER,
  size VARCHAR2(24 CHAR) NOT NULL,
  size_id NUMBER,
  price NUMBER(12,2) NOT NULL,
  cost_price NUMBER(12,2),
  quantity NUMBER(10) NOT NULL,
  active NUMBER(1) DEFAULT 1 NOT NULL,
  status NUMBER(1) DEFAULT 1 NOT NULL,
  CONSTRAINT uk_variant_sku UNIQUE (sku),
  CONSTRAINT uk_variant_barcode UNIQUE (barcode),
  CONSTRAINT fk_variant_product FOREIGN KEY (product_id) REFERENCES products(id),
  CONSTRAINT fk_variant_color FOREIGN KEY (color_id) REFERENCES colors(id),
  CONSTRAINT fk_variant_size FOREIGN KEY (size_id) REFERENCES sizes(id)
);

-- 16. Product Images (Bảng 2.35)
CREATE TABLE product_images (
  id NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  product_id NUMBER NOT NULL,
  variant_id NUMBER,
  color_id NUMBER,
  file_name VARCHAR2(120 CHAR) NOT NULL,
  image_url VARCHAR2(255 CHAR) NOT NULL,
  url_image VARCHAR2(255 CHAR),
  sort_order NUMBER(10) NOT NULL,
  is_primary NUMBER(1) DEFAULT 0 NOT NULL,
  main_image NUMBER(1) DEFAULT 0 NOT NULL,
  status NUMBER(1) DEFAULT 1 NOT NULL,
  CONSTRAINT fk_image_product FOREIGN KEY (product_id) REFERENCES products(id),
  CONSTRAINT fk_image_variant FOREIGN KEY (variant_id) REFERENCES product_details(id),
  CONSTRAINT fk_image_color FOREIGN KEY (color_id) REFERENCES colors(id)
);

-- 17. Fault Products (Bảng 2.26)
CREATE TABLE fault_products (
  id NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  product_detail_id NUMBER NOT NULL,
  quantity NUMBER(10) NOT NULL,
  description VARCHAR2(255 CHAR),
  status NUMBER(1) DEFAULT 1 NOT NULL,
  created_at TIMESTAMP NOT NULL,
  CONSTRAINT fk_fault_product_detail FOREIGN KEY (product_detail_id) REFERENCES product_details(id)
);

-- 18. Discounts (Bảng 2.33)
CREATE TABLE discounts (
  id NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  name VARCHAR2(255 CHAR) NOT NULL,
  description VARCHAR2(255 CHAR),
  start_date TIMESTAMP NOT NULL,
  end_date TIMESTAMP NOT NULL,
  status NUMBER(1) DEFAULT 1 NOT NULL
);

-- 19. Product Discounts (Bảng 2.34)
CREATE TABLE product_discounts (
  id NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  product_id NUMBER NOT NULL,
  discount_id NUMBER NOT NULL,
  percent NUMBER(10) NOT NULL,
  status NUMBER(1) DEFAULT 1 NOT NULL,
  CONSTRAINT fk_pdiscount_product FOREIGN KEY (product_id) REFERENCES products(id),
  CONSTRAINT fk_pdiscount_discount FOREIGN KEY (discount_id) REFERENCES discounts(id)
);

-- 20. Vouchers (Bảng 2.36)
CREATE TABLE vouchers (
  id NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  code VARCHAR2(64 CHAR) NOT NULL,
  name VARCHAR2(160 CHAR) NOT NULL,
  description VARCHAR2(255 CHAR),
  discount NUMBER(10) NOT NULL,
  min NUMBER(12,2),
  max NUMBER(12,2),
  start_date TIMESTAMP NOT NULL,
  end_date TIMESTAMP NOT NULL,
  type NUMBER(1) DEFAULT 0 NOT NULL,
  status NUMBER(1) DEFAULT 1 NOT NULL,
  CONSTRAINT uk_voucher_code UNIQUE (code)
);

-- 21. Checkouts (Bảng 2.40)
CREATE TABLE checkouts (
  id NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  code VARCHAR2(64 CHAR) NOT NULL,
  code_order VARCHAR2(64 CHAR),
  status NUMBER(2) DEFAULT 1 NOT NULL,
  total_amount NUMBER(12,2) DEFAULT 0,
  payment_type VARCHAR2(32 CHAR) DEFAULT 'COD',
  created_at TIMESTAMP NOT NULL
);

-- 22. Checkout Details (Bảng 2.41)
CREATE TABLE checkout_details (
  id NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  checkout_id NUMBER NOT NULL,
  product_detail_id NUMBER NOT NULL,
  quantity NUMBER(10) NOT NULL,
  price NUMBER(12,2),
  status NUMBER(2) DEFAULT 1 NOT NULL,
  CONSTRAINT fk_cd_checkout FOREIGN KEY (checkout_id) REFERENCES checkouts(id),
  CONSTRAINT fk_cd_product_detail FOREIGN KEY (product_detail_id) REFERENCES product_details(id)
);

-- 23. Orders / Customer Orders (Bảng 2.15)
CREATE TABLE customer_orders (
  id NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  code VARCHAR2(32 CHAR) NOT NULL,
  idempotency_key VARCHAR2(100 CHAR),
  request_hash VARCHAR2(64 CHAR),
  account_id NUMBER,
  customer_id NUMBER,
  employee_id NUMBER,
  voucher_id NUMBER,
  customer_name VARCHAR2(160 CHAR) NOT NULL,
  customer_email VARCHAR2(255 CHAR) NOT NULL,
  customer_phone VARCHAR2(32 CHAR) NOT NULL,
  ship_recipient_name VARCHAR2(160 CHAR) NOT NULL,
  ship_name VARCHAR2(160 CHAR),
  ship_phone VARCHAR2(32 CHAR) NOT NULL,
  ship_line1 VARCHAR2(255 CHAR) NOT NULL,
  address VARCHAR2(255 CHAR),
  ship_ward VARCHAR2(120 CHAR),
  ward_name VARCHAR2(120 CHAR),
  ship_district VARCHAR2(120 CHAR) NOT NULL,
  district_name VARCHAR2(120 CHAR),
  ship_province VARCHAR2(120 CHAR) NOT NULL,
  city_name VARCHAR2(120 CHAR),
  payment_method VARCHAR2(32 CHAR) NOT NULL,
  payment_type VARCHAR2(32 CHAR) DEFAULT 'COD',
  status_pay VARCHAR2(32 CHAR) DEFAULT 'UNPAID',
  channel VARCHAR2(24 CHAR) NOT NULL,
  sale_form VARCHAR2(32 CHAR) DEFAULT 'ONLINE',
  status VARCHAR2(32 CHAR) NOT NULL,
  voucher_code VARCHAR2(64 CHAR),
  subtotal NUMBER(12,2) NOT NULL,
  discount NUMBER(12,2) NOT NULL,
  shipping_fee NUMBER(12,2) NOT NULL,
  freight NUMBER(12,2) DEFAULT 0,
  total NUMBER(12,2) NOT NULL,
  note VARCHAR2(500 CHAR),
  created_by VARCHAR2(255 CHAR),
  created_at TIMESTAMP NOT NULL,
  updated_at TIMESTAMP NOT NULL,
  CONSTRAINT uk_order_code UNIQUE (code),
  CONSTRAINT uk_order_idempotency UNIQUE (idempotency_key),
  CONSTRAINT fk_order_account FOREIGN KEY (account_id) REFERENCES accounts(id),
  CONSTRAINT fk_order_customer FOREIGN KEY (customer_id) REFERENCES customers(id),
  CONSTRAINT fk_order_employee FOREIGN KEY (employee_id) REFERENCES employees(id),
  CONSTRAINT fk_order_voucher FOREIGN KEY (voucher_id) REFERENCES vouchers(id)
);

-- 24. Order Lines / Order Details (Bảng 2.39)
CREATE TABLE order_lines (
  id NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  order_id NUMBER NOT NULL,
  variant_id NUMBER,
  product_name VARCHAR2(200 CHAR) NOT NULL,
  sku VARCHAR2(64 CHAR) NOT NULL,
  color VARCHAR2(60 CHAR) NOT NULL,
  size VARCHAR2(24 CHAR) NOT NULL,
  image_url VARCHAR2(255 CHAR),
  quantity NUMBER(10) NOT NULL,
  return_quantity NUMBER(10) DEFAULT 0 NOT NULL,
  unit_price NUMBER(12,2) NOT NULL,
  discount NUMBER(12,2) DEFAULT 0,
  line_total NUMBER(12,2) NOT NULL,
  note VARCHAR2(255 CHAR),
  status NUMBER(2) DEFAULT 1 NOT NULL,
  CONSTRAINT fk_line_order FOREIGN KEY (order_id) REFERENCES customer_orders(id),
  CONSTRAINT fk_line_variant FOREIGN KEY (variant_id) REFERENCES product_details(id)
);

-- 25. Order Returns (Bảng 2.37)
CREATE TABLE order_returns (
  id NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  order_id NUMBER NOT NULL,
  account_id NUMBER NOT NULL,
  customer_id NUMBER,
  reason VARCHAR2(500 CHAR) NOT NULL,
  note VARCHAR2(255 CHAR),
  video VARCHAR2(255 CHAR),
  total NUMBER(12,2) DEFAULT 0,
  status VARCHAR2(24 CHAR) NOT NULL,
  created_at TIMESTAMP NOT NULL,
  updated_at TIMESTAMP NOT NULL,
  CONSTRAINT fk_return_order FOREIGN KEY (order_id) REFERENCES customer_orders(id),
  CONSTRAINT fk_return_account FOREIGN KEY (account_id) REFERENCES accounts(id),
  CONSTRAINT fk_return_customer FOREIGN KEY (customer_id) REFERENCES customers(id)
);

-- 26. Return Details (Bảng 2.38)
CREATE TABLE return_details (
  id NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  return_id NUMBER NOT NULL,
  order_detail_id NUMBER NOT NULL,
  quantity NUMBER(10) NOT NULL,
  status NUMBER(2) DEFAULT 1 NOT NULL,
  CONSTRAINT fk_rd_return FOREIGN KEY (return_id) REFERENCES order_returns(id),
  CONSTRAINT fk_rd_order_detail FOREIGN KEY (order_detail_id) REFERENCES order_lines(id)
);

-- 27. Exchanges (ERD Hình 2.31)
CREATE TABLE exchanges (
  id NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  customer_id NUMBER,
  return_id NUMBER,
  employee_id NUMBER,
  total NUMBER(12,2) DEFAULT 0,
  note VARCHAR2(255 CHAR),
  ship_address VARCHAR2(255 CHAR),
  ship_name VARCHAR2(160 CHAR),
  ship_phone VARCHAR2(32 CHAR),
  status_pay VARCHAR2(32 CHAR) DEFAULT 'PAID',
  freight NUMBER(12,2) DEFAULT 0,
  status VARCHAR2(32 CHAR) DEFAULT 'PENDING' NOT NULL,
  created_at TIMESTAMP NOT NULL,
  CONSTRAINT fk_exchange_customer FOREIGN KEY (customer_id) REFERENCES customers(id),
  CONSTRAINT fk_exchange_return FOREIGN KEY (return_id) REFERENCES order_returns(id),
  CONSTRAINT fk_exchange_employee FOREIGN KEY (employee_id) REFERENCES employees(id)
);

-- 28. Exchange Details (ERD Hình 2.31)
CREATE TABLE exchange_details (
  id NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  exchange_id NUMBER NOT NULL,
  product_detail_id NUMBER NOT NULL,
  quantity NUMBER(10) NOT NULL,
  unit_price NUMBER(12,2) DEFAULT 0,
  note VARCHAR2(255 CHAR),
  status NUMBER(2) DEFAULT 1 NOT NULL,
  CONSTRAINT fk_ed_exchange FOREIGN KEY (exchange_id) REFERENCES exchanges(id),
  CONSTRAINT fk_ed_product_detail FOREIGN KEY (product_detail_id) REFERENCES product_details(id)
);

-- 29. Reviews / Ratings (Bảng 2.28)
CREATE TABLE product_reviews (
  id NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  product_id NUMBER NOT NULL,
  account_id NUMBER NOT NULL,
  customer_id NUMBER,
  order_id NUMBER NOT NULL,
  rating NUMBER(10) NOT NULL,
  content VARCHAR2(1000 CHAR),
  status NUMBER(1) DEFAULT 1 NOT NULL,
  created_at TIMESTAMP NOT NULL,
  CONSTRAINT uk_review_order_product UNIQUE (order_id, product_id),
  CONSTRAINT fk_review_product FOREIGN KEY (product_id) REFERENCES products(id),
  CONSTRAINT fk_review_account FOREIGN KEY (account_id) REFERENCES accounts(id),
  CONSTRAINT fk_review_customer FOREIGN KEY (customer_id) REFERENCES customers(id),
  CONSTRAINT fk_review_order FOREIGN KEY (order_id) REFERENCES customer_orders(id)
);

-- 30. Rating Images (Bảng 2.27)
CREATE TABLE rating_images (
  id NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  rating_id NUMBER NOT NULL,
  image VARCHAR2(255 CHAR) NOT NULL,
  status NUMBER(1) DEFAULT 1 NOT NULL,
  CONSTRAINT fk_ri_rating FOREIGN KEY (rating_id) REFERENCES product_reviews(id)
);

-- 31. Banners (Bảng 2.25)
CREATE TABLE banners (
  id NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  title VARCHAR2(255 CHAR),
  content VARCHAR2(500 CHAR),
  type NUMBER(10) DEFAULT 1 NOT NULL,
  url VARCHAR2(255 CHAR) NOT NULL,
  link_url VARCHAR2(255 CHAR),
  status NUMBER(1) DEFAULT 1 NOT NULL,
  sort_order NUMBER(10) DEFAULT 0 NOT NULL
);

-- 32. Contacts (Bảng 2.32)
CREATE TABLE contacts (
  id NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  name VARCHAR2(120 CHAR) NOT NULL,
  phone VARCHAR2(32 CHAR) NOT NULL,
  email VARCHAR2(255 CHAR),
  address_name VARCHAR2(255 CHAR),
  ward VARCHAR2(120 CHAR),
  district VARCHAR2(120 CHAR),
  province VARCHAR2(120 CHAR),
  content VARCHAR2(1000 CHAR),
  status NUMBER(1) DEFAULT 1 NOT NULL,
  created_at TIMESTAMP NOT NULL
);

-- Audit & Operations Tables
CREATE TABLE order_status_history (
  id NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  order_id NUMBER NOT NULL,
  previous_status VARCHAR2(32 CHAR),
  next_status VARCHAR2(32 CHAR) NOT NULL,
  note VARCHAR2(500 CHAR),
  changed_by VARCHAR2(255 CHAR),
  created_at TIMESTAMP NOT NULL,
  CONSTRAINT fk_history_order FOREIGN KEY (order_id) REFERENCES customer_orders(id)
);

CREATE TABLE inventory_movements (
  id NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  variant_id NUMBER NOT NULL,
  movement_type VARCHAR2(32 CHAR) NOT NULL,
  quantity_delta NUMBER(10) NOT NULL,
  reference VARCHAR2(100 CHAR),
  created_by VARCHAR2(255 CHAR),
  created_at TIMESTAMP NOT NULL,
  CONSTRAINT fk_movement_variant FOREIGN KEY (variant_id) REFERENCES product_details(id)
);

CREATE TABLE promotions (
  id NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  name VARCHAR2(160 CHAR) NOT NULL,
  code VARCHAR2(64 CHAR) NOT NULL,
  description VARCHAR2(500 CHAR),
  percent_off NUMBER(3) NOT NULL,
  minimum_order NUMBER(12,2) NOT NULL,
  maximum_discount NUMBER(12,2),
  starts_at TIMESTAMP NOT NULL,
  ends_at TIMESTAMP NOT NULL,
  active NUMBER(1) DEFAULT 1 NOT NULL,
  CONSTRAINT uk_promotion_code UNIQUE (code)
);

-- Indexes
CREATE INDEX ix_product_category ON products(category_id, active);
CREATE INDEX ix_variant_product ON product_details(product_id, active);
CREATE INDEX ix_order_created_status ON customer_orders(created_at, status);
CREATE INDEX ix_order_account_created ON customer_orders(account_id, created_at);
